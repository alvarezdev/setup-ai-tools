#!/usr/bin/env bash
# Bootstrap multiplataforma de setup-ai-tools. Genera las instrucciones locales
# y ejecuta los provisionadores disponibles. Seguro al repetirse (idempotente).
set -euo pipefail

BASE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILLS_DST="$HOME/.claude/skills"
SETTINGS="$HOME/.claude/settings.json"
CODEX_HOME="${CODEX_HOME:-$HOME/.codex}"
CODEX_SKILLS_DST="$CODEX_HOME/skills"
VERSIONS="$BASE/tool-versions.env"
PLATFORM_REGISTRY="$BASE/platforms.txt"
INSTRUCTIONS_SOURCE="$BASE/PROJECT_INSTRUCTIONS.md"
GENERATED_MARKER='<!-- Generated by setup-ai-tools from PROJECT_INSTRUCTIONS.md. Do not edit directly. -->'
LEGACY_GENERATED_MARKER='<!-- Generated by setup-skills from PROJECT_INSTRUCTIONS.md. Do not edit directly. -->'
STATE_HOME="${XDG_STATE_HOME:-$HOME/.local/state}"
STATE_DIR="$STATE_HOME/setup-ai-tools"
STATE_FILE="$STATE_DIR/managed-roots"
STATE_MARKER="setup-ai-tools-managed-roots-v1"
LEGACY_STATE_DIR="$STATE_HOME/setup-skills"
LEGACY_STATE_FILE="$LEGACY_STATE_DIR/managed-roots"
LEGACY_STATE_MARKER="setup-skills-managed-roots-v1"
IMPORTED_LEGACY_STATE=0
MANAGED_ROOTS=""
SELECTED_PLATFORMS=""
MIGRATE_TOOLS=""
INSTALL_CONFLICTS=""
INSTRUCTIONS_ONLY=0

usage() {
  cat >&2 <<EOF
Uso: $0 [--platform <nombre>]... [--migrate-tool <nombre>]... [--instructions-only]

Sin --platform, detecta todos los CLI registrados disponibles en PATH.
--migrate-tool reemplaza symlinks externos solo para la herramienta indicada.
EOF
}

add_platform() {
  local platform="$1"
  if printf '%s\n' "$SELECTED_PLATFORMS" | grep -Fx "$platform" >/dev/null 2>&1; then
    return
  fi
  if [ -n "$SELECTED_PLATFORMS" ]; then
    SELECTED_PLATFORMS="$SELECTED_PLATFORMS
$platform"
  else
    SELECTED_PLATFORMS="$platform"
  fi
}

add_migrate_tool() {
  local tool="$1"
  if printf '%s\n' "$MIGRATE_TOOLS" | grep -Fx "$tool" >/dev/null 2>&1; then
    return
  fi
  if [ -n "$MIGRATE_TOOLS" ]; then
    MIGRATE_TOOLS="$MIGRATE_TOOLS
$tool"
  else
    MIGRATE_TOOLS="$tool"
  fi
}

migration_requested() {
  printf '%s\n' "$MIGRATE_TOOLS" | grep -Fx "$1" >/dev/null 2>&1
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --platform)
      [ "$#" -ge 2 ] || { usage; exit 2; }
      add_platform "$2"
      shift 2
      ;;
    --instructions-only)
      INSTRUCTIONS_ONLY=1
      shift
      ;;
    --migrate-tool)
      [ "$#" -ge 2 ] || { usage; exit 2; }
      add_migrate_tool "$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      usage
      exit 2
      ;;
  esac
done

while IFS= read -r migrate_tool; do
  [ -n "$migrate_tool" ] || continue
  case "$migrate_tool" in
    superpowers) ;;
    *)
      echo "ERROR: migracion no implementada para: $migrate_tool" >&2
      exit 2
      ;;
  esac
done <<EOF
$MIGRATE_TOOLS
EOF

if [ ! -f "$PLATFORM_REGISTRY" ] || [ ! -f "$INSTRUCTIONS_SOURCE" ]; then
  echo "ERROR: faltan platforms.txt o PROJECT_INSTRUCTIONS.md" >&2
  exit 1
fi

if [ -z "$SELECTED_PLATFORMS" ]; then
  SELECTED_PLATFORMS="$(
    while IFS='|' read -r platform cli_command version_argument instructions_file detail; do
      [ -n "$platform" ] || continue
      [ "${platform#\#}" = "$platform" ] || continue
      if command -v "$cli_command" >/dev/null 2>&1; then
        printf '%s\n' "$platform"
      fi
    done < "$PLATFORM_REGISTRY"
  )"
fi

if [ -z "$SELECTED_PLATFORMS" ]; then
  echo "ERROR: no se detecto ningun CLI registrado; usa --platform <nombre>" >&2
  exit 1
fi

generate_instruction_file() {
  local platform="$1"
  local instructions_file destination temporary first_line

  instructions_file="$(awk -F'|' -v wanted="$platform" '
    $1 !~ /^#/ && $1 == wanted { print $4; found = 1; exit }
    END { if (!found) exit 1 }
  ' "$PLATFORM_REGISTRY")" || {
    echo "ERROR: plataforma no registrada: $platform" >&2
    return 1
  }

  case "$instructions_file" in
    ''|*/*|*[!A-Za-z0-9._-]*)
      echo "ERROR: archivo de instrucciones invalido para $platform: $instructions_file" >&2
      return 1
      ;;
  esac

  destination="$BASE/$instructions_file"
  if [ -L "$destination" ]; then
    echo "ERROR: $destination es un symlink; no se reemplaza" >&2
    return 1
  fi
  if [ -e "$destination" ]; then
    if [ ! -f "$destination" ]; then
      echo "ERROR: $destination existe y no es un archivo regular" >&2
      return 1
    fi
    first_line="$(sed -n '1p' "$destination")"
    case "$first_line" in
      "$GENERATED_MARKER"|"$LEGACY_GENERATED_MARKER") ;;
      *)
        echo "ERROR: $destination no es administrado por setup-ai-tools; se conserva" >&2
        return 1
        ;;
    esac
  fi

  temporary="$(mktemp "$BASE/.instructions.XXXXXX")"
  {
    printf '%s\n\n' "$GENERATED_MARKER"
    cat "$INSTRUCTIONS_SOURCE"
  } > "$temporary"

  if [ -f "$destination" ] && cmp -s "$temporary" "$destination"; then
    rm -f "$temporary"
    echo "OK  $instructions_file ya esta actualizado para $platform"
    return
  fi

  mv "$temporary" "$destination"
  echo "OK  $instructions_file generado para $platform"
}

printf '%s\n' "$SELECTED_PLATFORMS" | while IFS= read -r platform; do
  [ -n "$platform" ] || continue
  generate_instruction_file "$platform"
done

if [ "$INSTRUCTIONS_ONLY" -eq 1 ]; then
  echo "==> Archivos de instrucciones listos"
  exit 0
fi

if [ ! -x "$BASE/verify-compatibility.sh" ]; then
  echo "ERROR: falta el verificador ejecutable $BASE/verify-compatibility.sh" >&2
  exit 1
fi

verify_selected_platforms() {
  local phase="$1"
  local result output
  printf '%s\n' "$SELECTED_PLATFORMS" | while IFS= read -r platform; do
    [ -n "$platform" ] || continue
    if [ "$phase" = "pre" ]; then
      if output="$("$BASE/verify-compatibility.sh" --platform "$platform" --phase "$phase" 2>&1)"; then
        continue
      else
        result=$?
      fi
      if [ "$result" -eq 2 ]; then
        continue
      fi
      printf '%s\n' "$output" >&2
      return "$result"
    fi

    if "$BASE/verify-compatibility.sh" --platform "$platform" --phase "$phase"; then
      continue
    else
      result=$?
    fi
    if [ "$result" -eq 2 ]; then
      echo "AVISO: $platform requiere adaptadores; se continuara con lo disponible" >&2
    else
      return "$result"
    fi
  done
}

platform_is_selected() {
  printf '%s\n' "$SELECTED_PLATFORMS" | grep -Fx "$1" >/dev/null 2>&1
}

add_managed_root() {
  local root="$1"
  [ -n "$root" ] || return
  case "$root" in
    /*) ;;
    *)
      echo "ERROR: ruta administrada invalida: $root" >&2
      return 1
      ;;
  esac
  if printf '%s\n' "$MANAGED_ROOTS" | grep -Fx "$root" >/dev/null 2>&1; then
    return
  fi
  if [ -n "$MANAGED_ROOTS" ]; then
    MANAGED_ROOTS="$MANAGED_ROOTS
$root"
  else
    MANAGED_ROOTS="$root"
  fi
}

load_install_state_file() {
  local state_file="$1"
  local expected_marker="$2"
  local marker root count=0
  if [ -L "$state_file" ]; then
    echo "ERROR: $state_file es un symlink; no se utiliza" >&2
    return 1
  fi
  if [ ! -e "$state_file" ]; then
    return
  fi
  if [ ! -f "$state_file" ]; then
    echo "ERROR: $state_file existe y no es un archivo regular" >&2
    return 1
  fi

  {
    IFS= read -r marker || {
      echo "ERROR: estado de instalacion vacio: $state_file" >&2
      return 1
    }
    if [ "$marker" != "$expected_marker" ]; then
      echo "ERROR: estado de instalacion no reconocido: $state_file" >&2
      return 1
    fi
    while IFS= read -r root; do
      [ -n "$root" ] || {
        echo "ERROR: ruta vacia en $state_file" >&2
        return 1
      }
      add_managed_root "$root"
      count=$((count + 1))
    done
  } < "$state_file"

  if [ "$count" -eq 0 ]; then
    echo "ERROR: $state_file no declara ninguna ruta administrada" >&2
    return 1
  fi
}

load_install_state() {
  if [ -e "$STATE_FILE" ] || [ -L "$STATE_FILE" ]; then
    load_install_state_file "$STATE_FILE" "$STATE_MARKER"
    return
  fi

  if [ -e "$LEGACY_STATE_FILE" ] || [ -L "$LEGACY_STATE_FILE" ]; then
    load_install_state_file "$LEGACY_STATE_FILE" "$LEGACY_STATE_MARKER"
    IMPORTED_LEGACY_STATE=1
    echo "==> Estado anterior importado desde: $LEGACY_STATE_DIR"
  fi
}

import_legacy_migration_log() {
  local old_log="$LEGACY_STATE_DIR/migrations.log"
  local new_log="$STATE_DIR/migrations.log"
  [ "$IMPORTED_LEGACY_STATE" -eq 1 ] || return 0
  [ -e "$old_log" ] || [ -L "$old_log" ] || return 0

  if [ -L "$old_log" ] || [ ! -f "$old_log" ]; then
    echo "ERROR: historial anterior invalido: $old_log" >&2
    return 1
  fi
  if [ -e "$new_log" ] || [ -L "$new_log" ]; then
    echo "AVISO: ya existe $new_log; el historial anterior se conserva en $old_log" >&2
    return 0
  fi

  mkdir -p "$STATE_DIR"
  cp "$old_log" "$new_log"
  chmod 600 "$new_log"
  echo "OK  historial de migraciones importado desde setup-skills"
}

LEGACY_ROOT=""
LEGACY_MATCHES=0
LEGACY_CONFLICT=0

consider_legacy_symlink() {
  local link="$1"
  local relative_target="$2"
  local raw suffix candidate
  [ -L "$link" ] || return 0
  raw="$(readlink "$link")"
  case "$raw" in /*) ;; *) return 0 ;; esac
  [ ! -e "$raw" ] || return 0
  suffix="/$relative_target"
  case "$raw" in
    *"$suffix") candidate="${raw%"$suffix"}" ;;
    *) return 0 ;;
  esac
  [ -n "$candidate" ] || return 0
  [ "$candidate" != "/" ] || return 0
  if [ -n "$LEGACY_ROOT" ] && [ "$LEGACY_ROOT" != "$candidate" ]; then
    LEGACY_CONFLICT=1
    return 0
  fi
  LEGACY_ROOT="$candidate"
  LEGACY_MATCHES=$((LEGACY_MATCHES + 1))
}

discover_legacy_root() {
  [ -z "$MANAGED_ROOTS" ] || return 0

  consider_legacy_symlink "$SKILLS_DST/commit-style" "skills/commit-style"
  consider_legacy_symlink "$SKILLS_DST/using-superpowers" "superpowers/skills/using-superpowers"
  consider_legacy_symlink "$CODEX_SKILLS_DST/commit-style" "skills/commit-style"
  consider_legacy_symlink "$CODEX_SKILLS_DST/using-superpowers" "superpowers/skills/using-superpowers"

  if [ "$LEGACY_CONFLICT" -eq 0 ] && [ "$LEGACY_MATCHES" -ge 2 ]; then
    add_managed_root "$LEGACY_ROOT"
    echo "==> Instalacion anterior detectada en: $LEGACY_ROOT"
  fi
  return 0
}

write_install_state() {
  local temporary root
  add_managed_root "$BASE"
  if [ -L "$STATE_FILE" ]; then
    echo "ERROR: $STATE_FILE es un symlink; no se reemplaza" >&2
    return 1
  fi
  if [ -e "$STATE_FILE" ] && [ ! -f "$STATE_FILE" ]; then
    echo "ERROR: $STATE_FILE existe y no es un archivo regular" >&2
    return 1
  fi
  mkdir -p "$STATE_DIR"
  temporary="$(mktemp "$STATE_DIR/.managed-roots.XXXXXX")"
  {
    printf '%s\n' "$STATE_MARKER"
    printf '%s\n' "$BASE"
    while IFS= read -r root; do
      [ -n "$root" ] || continue
      [ "$root" = "$BASE" ] && continue
      printf '%s\n' "$root"
    done <<EOF
$MANAGED_ROOTS
EOF
  } > "$temporary"
  chmod 600 "$temporary"
  mv "$temporary" "$STATE_FILE"
  echo "OK  ruta administrada registrada: $BASE"
}

load_install_state
import_legacy_migration_log
discover_legacy_root

if platform_is_selected claude || platform_is_selected codex; then
  if [ ! -f "$VERSIONS" ]; then
