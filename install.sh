writing-skills|$BASE/superpowers/skills/writing-skills
context7-mcp|$BASE/context7/plugins/codex/context7/skills/context7-mcp
"

  echo "$CODEX_SKILL_LINKS" | while IFS='|' read -r name target; do
    [ -z "$name" ] && continue
    link="$CODEX_SKILLS_DST/$name"
    if [ ! -d "$target" ]; then
      echo "AVISO: falta $target - se omite $name para Codex"
      continue
    fi

    target_resolved="$(cd "$target" && pwd -P)"
    if [ -L "$link" ]; then
      link_resolved="$(resolve_symlink_dir "$link" || true)"
      if [ "$link_resolved" = "$target_resolved" ]; then
        echo "OK  Codex/$name ya apunta al destino administrado"
        continue
      fi
      echo "ERROR: $link es un symlink administrado por otra fuente" >&2
      exit 1
    elif [ -e "$link" ]; then
      echo "ERROR: $link existe y no es un symlink; no se reemplaza" >&2
      exit 1
    fi

    ln -s "$target" "$link"
    echo "OK  Codex/$name -> $target"
  done
fi

# --- 4. claude-mem: integraciones seleccionadas + worker ----------------
if platform_is_selected claude || platform_is_selected codex; then
  echo "==> Instalando claude-mem $CLAUDE_MEM_VERSION"
  if ! command -v npx >/dev/null 2>&1; then
    echo "ERROR: npx no esta disponible; instala Node.js y vuelve a ejecutar install.sh" >&2
    exit 1
  fi
  if platform_is_selected claude; then
    (cd "$BASE" && npx "claude-mem@$CLAUDE_MEM_VERSION" install --ide claude-code </dev/null)
  fi
  if platform_is_selected codex; then
    (cd "$BASE" && npx "claude-mem@$CLAUDE_MEM_VERSION" install --ide codex-cli </dev/null)
  fi
  (cd "$BASE" && npx "claude-mem@$CLAUDE_MEM_VERSION" start)
fi

# --- 5. Context7 MCP por plataforma -------------------------------------
if platform_is_selected claude; then
  echo "==> Registrando Context7 para Claude (scope user)"
  if claude mcp get context7 >/dev/null 2>&1; then
    echo "OK  Context7 ya estaba registrado en Claude"
  else
    claude mcp add --transport http context7 https://mcp.context7.com/mcp -s user
  fi
fi

if platform_is_selected codex; then
  echo "==> Registrando Context7 para Codex"
  if codex mcp get context7 >/dev/null 2>&1; then
    echo "OK  Context7 ya estaba registrado en Codex"
  else
    codex mcp add context7 --url https://mcp.context7.com/mcp
  fi
fi

# --- 6. Resumen -----------------------------------------------------------
cat <<'EOF'

