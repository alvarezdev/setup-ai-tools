normalize_git_url() {
  local value="${1%/}"
  printf '%s\n' "${value%.git}"
}

is_plain_semver() {
  awk -v version="$1" 'BEGIN { exit (version ~ /^[0-9]+\.[0-9]+\.[0-9]+$/ ? 0 : 1) }'
}

semver_is_greater() {
  awk -v candidate="$1" -v reference="$2" '
    BEGIN {
      split(candidate, candidate_parts, ".")
      split(reference, reference_parts, ".")
      for (part_index = 1; part_index <= 3; part_index++) {
        candidate_part = candidate_parts[part_index] + 0
        reference_part = reference_parts[part_index] + 0
        if (candidate_part > reference_part) exit 0
        if (candidate_part < reference_part) exit 1
      }
      exit 1
    }
  '
}

highest_installed_claude_mem_version() {
  local cache_root candidate version highest=""

  for cache_root in \
    "$HOME/.claude/plugins/cache/thedotmack/claude-mem" \
    "$CODEX_HOME/plugins/cache/claude-mem-local/claude-mem"; do
    [ -d "$cache_root" ] || continue
    for candidate in "$cache_root"/*; do
      [ -d "$candidate" ] || continue
      version="${candidate##*/}"
      is_plain_semver "$version" || continue
      if [ -z "$highest" ] || semver_is_greater "$version" "$highest"; then
        highest="$version"
      fi
    done
  done

  printf '%s\n' "$highest"
}

validate_repo_source() {
  local name="$1"
  local dest="$2"
  local required

  case "$name" in
    superpowers) required="skills/using-superpowers/SKILL.md" ;;
    prompt-master) required="SKILL.md" ;;
    abogado-del-diablo) required="skills/abogado-del-diablo/SKILL.md" ;;
    the-architect) required="CLAUDE.md" ;;
    context7) required="packages/mcp/package.json" ;;
    claude-token-efficient) required="CLAUDE.md" ;;
    *) required="README.md" ;;
  esac

  if [ ! -f "$dest/$required" ]; then
    echo "ERROR: $name no contiene el archivo esperado: $required" >&2
    return 1
  fi
}

ensure_clean_tracked_state() {
  local name="$1"
  local dest="$2"
  if ! git -C "$dest" diff --quiet || ! git -C "$dest" diff --cached --quiet; then
    echo "ERROR: $name tiene cambios rastreados; guardalos antes de reconciliar la version" >&2
    return 1
  fi
}

reconcile_repo() {
  local name="$1"
  local url="$2"
  local branch="$3"
  local commit="$4"
  local mode="$5"
  local dest="$BASE/$name"
  local current_url current_commit desired_commit

  case "$mode" in
    pinned)
      if [ -z "$commit" ] || [ "$commit" = "-" ]; then
        echo "ERROR: $name esta en modo pinned pero no declara commit" >&2
        return 1
      fi
      ;;
    shallow) ;;
    *)
      echo "ERROR: modo desconocido para $name: $mode" >&2
      return 1
      ;;
  esac

  if [ -e "$dest" ] && [ ! -d "$dest/.git" ]; then
    echo "ERROR: $dest existe pero no es un repositorio Git administrable" >&2
    return 1
  fi

  if [ ! -d "$dest/.git" ]; then
    if [ "$mode" = "shallow" ]; then
      echo "==> clone shallow $name ($branch)"
      git clone --depth 1 --branch "$branch" "$url" "$dest"
    else
      echo "==> clone $name (pinned $commit)"
      git clone "$url" "$dest"
      git -C "$dest" checkout --detach "$commit"
    fi
    validate_repo_source "$name" "$dest"
    return
  fi

  current_url="$(git -C "$dest" config --get remote.origin.url || true)"
  if [ -z "$current_url" ] || [ "$(normalize_git_url "$current_url")" != "$(normalize_git_url "$url")" ]; then
    echo "ERROR: $name existe pero su origin no coincide" >&2
    echo "  Actual:   ${current_url:-(sin origin)}" >&2
    echo "  Esperado: $url" >&2
    return 1
  fi

  current_commit="$(git -C "$dest" rev-parse HEAD)"
  if [ "$mode" = "pinned" ]; then
    desired_commit="$commit"
    if [ "$current_commit" = "$desired_commit" ]; then
      echo "OK  $name coincide con el commit fijado ($desired_commit)"
      validate_repo_source "$name" "$dest"
      return
    fi

    ensure_clean_tracked_state "$name" "$dest"
    if ! git -C "$dest" cat-file -e "$desired_commit^{commit}" 2>/dev/null; then
      git -C "$dest" fetch origin "$desired_commit"
    fi
  else
    git -C "$dest" fetch origin "$branch"
    desired_commit="$(git -C "$dest" rev-parse FETCH_HEAD)"
    if [ "$current_commit" = "$desired_commit" ]; then
      echo "OK  $name ya coincide con el ultimo commit de $branch ($desired_commit)"
      validate_repo_source "$name" "$dest"
      return
    fi
    ensure_clean_tracked_state "$name" "$dest"
  fi

  echo "==> Reconciliando $name: $current_commit -> $desired_commit"
  git -C "$dest" checkout --detach "$desired_commit"
  validate_repo_source "$name" "$dest"
}

resolve_symlink_dir() {
  local link="$1"
  local raw candidate
  raw="$(readlink "$link")"
  case "$raw" in
    /*) candidate="$raw" ;;
    *) candidate="$(dirname "$link")/$raw" ;;
  esac
  (cd "$candidate" 2>/dev/null && pwd -P)
}

symlink_uses_managed_root() {
  local link="$1"
  local target="$2"
  local raw relative_target root
  raw="$(readlink "$link")"
  relative_target="${target#"$BASE"/}"
  [ "$relative_target" != "$target" ] || return 1

  while IFS= read -r root; do
    [ -n "$root" ] || continue
    if [ "$raw" = "$root/$relative_target" ]; then
      return 0
    fi
  done <<EOF
$MANAGED_ROOTS
EOF
  return 1
}

ensure_skill_link() {
  local platform="$1"
  local tool="$2"
  local label="$3"
  local link="$4"
  local target="$5"
  local target_resolved link_resolved

  target_resolved="$(cd "$target" && pwd -P)"
  if [ -L "$link" ]; then
    link_resolved="$(resolve_symlink_dir "$link" || true)"
    if [ "$link_resolved" = "$target_resolved" ]; then
      echo "OK  $label ya apunta al destino administrado"
      return
    fi
    if symlink_uses_managed_root "$link" "$target"; then
      echo "MIG $label: $(readlink "$link") -> $target"
      ln -sfn "$target" "$link"
      return
    fi
    if migration_requested "$tool"; then
      append_migration_record "$platform" "$tool" "$(readlink "$link")" "-" "-" "$target"
      echo "MIG $label externo: $(readlink "$link") -> $target"
      ln -sfn "$target" "$link"
      return
    fi
    add_install_conflict "$platform/$tool: se conserva $link -> $(readlink "$link")"
    echo "AVISO: $link pertenece a otra instalacion; se conserva y se omite $label" >&2
    return 0
  fi
  if [ -e "$link" ]; then
    if migration_requested "$tool"; then
      echo "ERROR: $link es una carpeta o archivo real; la migracion nunca lo reemplaza" >&2
      return 1
    fi
    add_install_conflict "$platform/$tool: se conserva el destino real $link"
    echo "AVISO: $link es un destino real; se conserva y se omite $label" >&2
    return 0
  fi

  ln -s "$target" "$link"
  echo "OK  $label -> $target"
}

install_managed_instruction_block() {
  local platform="$1"
  local feature="$2"
  local destination="$3"
  local source="$4"
  local override="${5:-}"
  local status
  local marker_begin="# >>> setup-ai-tools: $feature >>>"
  local marker_end="# <<< setup-ai-tools: $feature <<<"

  if [ ! -f "$source" ]; then
    echo "ERROR: falta la fuente de $feature: $source" >&2
    return 1
  fi

  if [ -n "$override" ] && [ -f "$override" ] && [ -s "$override" ]; then
    add_install_conflict "$platform/$feature: $(basename "$override") no vacio puede ocultar $destination"
    echo "AVISO: $override no vacio puede impedir que $platform lea $destination" >&2
  fi

  if [ -L "$destination" ]; then
    add_install_conflict "$platform/$feature: $(basename "$destination") es un symlink; se conserva"
    echo "AVISO: $destination es un symlink; se conserva y se omite $feature" >&2
    return 0
  fi
  if [ -e "$destination" ] && [ ! -f "$destination" ]; then
    add_install_conflict "$platform/$feature: $(basename "$destination") existe y no es un archivo regular; se conserva"
    echo "AVISO: $destination existe y no es un archivo regular; se conserva y se omite $feature" >&2
    return 0
  fi

  if python3 - "$destination" "$source" "$marker_begin" "$marker_end" "$feature" <<'PYEOF'
import os
import re
import stat
import sys
import tempfile

destination_path, source_path, begin, end, feature = sys.argv[1:]

with open(source_path, encoding="utf-8") as f:
    source = f.read()

if begin in source or end in source:
    print(
        f"ERROR: la fuente de {feature} contiene marcadores administrados",
        file=sys.stderr,
    )
    raise SystemExit(4)

if os.path.exists(destination_path):
    with open(destination_path, encoding="utf-8") as f:
        current = f.read()
else:
    current = ""

lines = current.splitlines(keepends=True)
line_contents = [line.rstrip("\r\n") for line in lines]
begin_indexes = [
    index for index, line in enumerate(line_contents) if line == begin
]
end_indexes = [
    index for index, line in enumerate(line_contents) if line == end
]
has_marker_variant = any(
    line.startswith(begin) and line != begin for line in line_contents
) or any(
    line.startswith(end) and line != end for line in line_contents
)

managed_begin = re.compile(r"^# >>> setup-ai-tools: ([A-Za-z0-9._-]+) >>>$")
managed_end = re.compile(r"^# <<< setup-ai-tools: ([A-Za-z0-9._-]+) <<<$")
active = None
all_markers_valid = True
for line in line_contents:
    begin_match = managed_begin.fullmatch(line)
    end_match = managed_end.fullmatch(line)
    if line.startswith("# >>> setup-ai-tools:") and begin_match is None:
        all_markers_valid = False
        break
    if line.startswith("# <<< setup-ai-tools:") and end_match is None:
        all_markers_valid = False
        break
    if begin_match:
        if active is not None:
            all_markers_valid = False
            break
        active = begin_match.group(1)
    elif end_match:
        if active != end_match.group(1):
            all_markers_valid = False
            break
        active = None
if active is not None:
    all_markers_valid = False

if has_marker_variant or not all_markers_valid:
    print(
        f"AVISO: {destination_path} contiene marcadores administrados corruptos; se conserva",
        file=sys.stderr,
    )
    raise SystemExit(3)
elif not begin_indexes and not end_indexes:
    prefix = current
    if prefix and not prefix.endswith(("\n", "\r")):
        prefix += "\n"
    updated = prefix + begin + "\n" + source
    if not updated.endswith(("\n", "\r")):
        updated += "\n"
    updated += end + "\n"
elif len(begin_indexes) == 1 and len(end_indexes) == 1 and begin_indexes[0] < end_indexes[0]:
    source_block = source
    if source_block and not source_block.endswith(("\n", "\r")):
        source_block += "\n"
    updated = "".join(lines[:begin_indexes[0]])
    updated += begin + "\n" + source_block + end + "\n"
    updated += "".join(lines[end_indexes[0] + 1:])
else:
    print(
        f"AVISO: {destination_path} contiene marcadores administrados corruptos; se conserva",
        file=sys.stderr,
    )
    raise SystemExit(3)

directory = os.path.dirname(destination_path)
os.makedirs(directory, exist_ok=True)
fd, temporary = tempfile.mkstemp(prefix=".instructions.", suffix=".md", dir=directory)
try:
    with os.fdopen(fd, "w", encoding="utf-8") as f:
        f.write(updated)
        f.flush()
        os.fsync(f.fileno())
    if os.path.exists(destination_path):
        os.chmod(temporary, stat.S_IMODE(os.stat(destination_path).st_mode))
    os.replace(temporary, destination_path)
except Exception:
    try:
        os.unlink(temporary)
    except FileNotFoundError:
        pass
    raise
PYEOF
  then
    echo "OK  $feature actualizado en $destination"
    return 0
  else
    status=$?
  fi

  if [ "$status" -eq 3 ]; then
    add_install_conflict "$platform/$feature: marcadores administrados corruptos en $(basename "$destination"); se conserva"
    return 0
  fi
  return "$status"
}

add_install_conflict() {
  local detail="$1"
  if printf '%s\n' "$INSTALL_CONFLICTS" | grep -Fx "$detail" >/dev/null 2>&1; then
    return
  fi
  if [ -n "$INSTALL_CONFLICTS" ]; then
    INSTALL_CONFLICTS="$INSTALL_CONFLICTS
$detail"
  else
    INSTALL_CONFLICTS="$detail"
  fi
}

append_migration_record() {
  local platform="$1"
  local tool="$2"
  local previous_target="$3"
  local previous_origin="$4"
  local previous_commit="$5"
  local new_target="$6"
  local log_file="$STATE_DIR/migrations.log"
  local temporary

  if [ -L "$log_file" ]; then
    echo "ERROR: $log_file es un symlink; no se registra la migracion" >&2
    return 1
  fi
  if [ -e "$log_file" ] && [ ! -f "$log_file" ]; then
    echo "ERROR: $log_file existe y no es un archivo regular" >&2
    return 1
  fi
  mkdir -p "$STATE_DIR"
  temporary="$(mktemp "$STATE_DIR/.migrations.XXXXXX")"
  if [ -f "$log_file" ]; then
    cp "$log_file" "$temporary"
  fi
  {
    printf '%s\n' '---'
    printf 'timestamp=%s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')"
    printf 'platform=%s\n' "$platform"
    printf 'tool=%s\n' "$tool"
    printf 'previous_target=%s\n' "$previous_target"
    printf 'previous_origin=%s\n' "$previous_origin"
    printf 'previous_commit=%s\n' "$previous_commit"
    printf 'new_target=%s\n' "$new_target"
  } >> "$temporary"
  chmod 600 "$temporary"
  mv "$temporary" "$log_file"
}

