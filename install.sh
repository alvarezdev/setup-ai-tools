prepare_superpowers_for_platform() {
  local platform="$1"
  local link="$2"
  local managed_target="$BASE/superpowers/skills/using-superpowers"
  local raw suffix external_root external_origin external_commit expected_origin expected_commit detail

  if migration_requested superpowers; then
    validate_superpowers_migration_destinations "$platform" "$(dirname "$link")"
  fi

  [ -e "$link" ] || [ -L "$link" ] || return 0

  if [ ! -L "$link" ]; then
    if migration_requested superpowers; then
      echo "ERROR: $link es un destino real; mueve esa instalacion manualmente antes de migrar" >&2
      return 1
    fi
    detail="$platform/superpowers: destino real existente en $link; se conserva"
    add_install_conflict "$detail"
    skip_superpowers "$platform"
    return 0
  fi

  if symlink_uses_managed_root "$link" "$managed_target"; then
    return 0
  fi

  raw="$(readlink "$link")"
  if [ "$(resolve_symlink_dir "$link" || true)" = "$(cd "$managed_target" && pwd -P)" ]; then
    return 0
  fi

  suffix="/skills/using-superpowers"
  case "$raw" in
    *"$suffix") external_root="${raw%"$suffix"}" ;;
    *) external_root="" ;;
  esac
  external_origin="-"
  external_commit="-"
  if [ -n "$external_root" ] && [ -d "$external_root/.git" ]; then
    external_origin="$(git -C "$external_root" config --get remote.origin.url || true)"
    external_commit="$(git -C "$external_root" rev-parse HEAD 2>/dev/null || true)"
  fi
  expected_origin="$(git -C "$BASE/superpowers" config --get remote.origin.url)"
  expected_commit="$(git -C "$BASE/superpowers" rev-parse HEAD)"

  if [ -n "$external_root" ] \
    && [ "$(normalize_git_url "$external_origin")" = "$(normalize_git_url "$expected_origin")" ] \
    && [ "$external_commit" = "$expected_commit" ] \
    && [ -z "$(git -C "$external_root" status --porcelain)" ]; then
    set_superpowers_root "$platform" "$external_root"
    echo "REUSE $platform/superpowers desde $external_root ($external_commit)"
    return 0
  fi

  if migration_requested superpowers; then
    append_migration_record "$platform" superpowers "${external_root:-$raw}" \
      "$external_origin" "$external_commit" "$BASE/superpowers"
    echo "==> Migracion autorizada para $platform/superpowers"
    return 0
  fi

  detail="$platform/superpowers: externa=${external_origin}@${external_commit}, declarada=${expected_origin}@${expected_commit}; se conserva"
  add_install_conflict "$detail"
  skip_superpowers "$platform"
  echo "AVISO: Superpowers externo difiere para $platform; se conserva y se omite" >&2
}

